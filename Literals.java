public class Literals {
    static void main(String[] args) {
        byte age = 19; //integral literal
        short age1 = 19; //integral literal
        int age2 = 19; //integral literal
        long age3 = 19897047L; //integral literal
        char ch = 'a'; //character literal
        float f1 = 5.78f; //decimal literal
        double d1 = 4.8970d; //decimal literal
        boolean bool = true; //boolean literal
        System.out.println(bool);
        String str = "Nandita";
        System.out.println(str);
    }

}
